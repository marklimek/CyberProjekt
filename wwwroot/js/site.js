document.addEventListener("DOMContentLoaded", function () {
    // Funkcja inicjująca Tom Select dla wszystkich elementów z klasą .searchable-select
    document.querySelectorAll('.searchable-select').forEach((el) => {
        new TomSelect(el, {
            create: false,
            sortField: {
                field: "text",
                direction: "asc"
            }
        });
    });
});